import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const caps = JSON.parse(
  fs.readFileSync(path.join(ROOT, "src/projects/keramat/captions.json"), "utf-8"),
);

/**
 * Whisper tokens corrected to the script's intended wording (Script.docx).
 * Timing comes from the audio; spelling comes from the script.
 */
const CORRECTIONS = {
  // keys are lowercase — lookup uses text.toLowerCase()
  horror: "horor",
  '"found': "Found",
  'indonesia"': "Indonesia",
  didirekt: "di-direct",
  "tewa.": "Tiwa.",
  crew: "kru",
  cuman: "cuma",
  pake: "pakai",
  enggak: "nggak",
  "shooting.": "syuting.",
  shooting: "syuting",
};

const words = caps.map((c) => {
  let text = c.text.trim();
  const fixed = CORRECTIONS[text.toLowerCase()];
  if (fixed !== undefined) text = fixed;
  return {
    text,
    startMs: c.startMs,
    endMs: c.endMs,
    hasLeadingSpace: c.text.startsWith(" "),
  };
});

const phrases = [];
let currentPhrase = [];
let pId = 1;

words.forEach((w, idx) => {
  currentPhrase.push(w);
  const isPunct = /[.!?]$/.test(w.text);
  const isComma = /[,]$/.test(w.text);
  if (
    currentPhrase.length >= 5 ||
    isPunct ||
    (isComma && currentPhrase.length >= 3) ||
    idx === words.length - 1
  ) {
    phrases.push({
      id: pId++,
      startMs: currentPhrase[0].startMs,
      endMs: currentPhrase[currentPhrase.length - 1].endMs,
      words: currentPhrase,
    });
    currentPhrase = [];
  }
});

const ts = `// AUTO-GENERATED by scripts/generate-keramat-subtitles.mjs
// Word timings from whisper.cpp (lang=id); spelling corrected to Script.docx.
export type SubtitleWord = {
  text: string;
  startMs: number;
  endMs: number;
  hasLeadingSpace: boolean;
};

export type SubtitlePhrase = {
  id: number;
  startMs: number;
  endMs: number;
  words: SubtitleWord[];
};

export const SUBTITLE_WORDS: SubtitleWord[] = ${JSON.stringify(words, null, 2)
  .replace(/"text":/g, "text:")
  .replace(/"startMs":/g, "startMs:")
  .replace(/"endMs":/g, "endMs:")
  .replace(/"hasLeadingSpace":/g, "hasLeadingSpace:")};

export const SUBTITLE_PHRASES: SubtitlePhrase[] = ${JSON.stringify(phrases, null, 2)
  .replace(/"id":/g, "id:")
  .replace(/"text":/g, "text:")
  .replace(/"startMs":/g, "startMs:")
  .replace(/"endMs":/g, "endMs:")
  .replace(/"words":/g, "words:")
  .replace(/"hasLeadingSpace":/g, "hasLeadingSpace:")};

export const EMPHASIS_WORDS = new Set([
  "Keramat",
  "Tiwa.",
  "2009",
  "ngerekam.",
  "aneh",
  "kerekam",
  "bagus.",
  "Goyangannya,",
  "sudut",
  "nyorot",
  "ngeri",
  "frame.",
  "salah.",
]);

export const NARRATION_OFFSET_MS = 0;
`;

fs.writeFileSync(path.join(ROOT, "src/projects/keramat/subtitles.ts"), ts);
console.log(
  "keramat subtitles.ts written —",
  words.length,
  "words,",
  phrases.length,
  "phrases",
);
