/**
 * generate-subtitles.mjs — Interstellar production
 * Reads whisper word-level captions and emits src/projects/interstellar/subtitles.ts
 * with cleanup fixes:
 *  - strips leading spaces into a flag instead of text
 *  - whisper split "di tanam" -> "ditanam" (narration wording)
 *  - punctuation snapping: "anaknya." before "Murph," -> comma
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const caps = JSON.parse(
  fs.readFileSync(path.join(ROOT, "src/projects/interstellar/captions.json"), "utf-8"),
);

// whisper sometimes splits contractions; merge pairs where 2nd word is an orphan suffix
const JOIN = [["di", "tanam", "ditanam"]];
// whisper spelling artifacts -> intended narration text
const FIXED_TEXT = [
  ["cinematografinya", "sinematografinya"],
];
// punctuation snapping: these words end with '.' although narration continues
const DEDOT = ["anaknya."];

const words = [];
let i = 0;
const raw = caps.map((c) => ({
  text: c.text,
  startMs: c.startMs,
  endMs: c.endMs,
}));

while (i < raw.length) {
  let w = { ...raw[i] };
  const next = raw[i + 1];
  // join fixes ("di" + "tanam" -> "ditanam")
  if (next) {
    const a = w.text.trim().replace(/[.,]$/, "").toLowerCase();
    const b = next.text.trim().replace(/[.,]$/, "").toLowerCase();
    const pair = JOIN.find(([x, y]) => a === x && b === y);
    if (pair) {
      const combined = pair[2] + (next.text.trim().endsWith(",") ? "," : w.text.trim().endsWith(",") ? "," : "");
      w = {
        text: combined,
        startMs: w.startMs,
        endMs: next.endMs,
      };
      i += 2;
      words.push(w);
      continue;
    }
  }
  if (DEDOT.includes(w.text.trim())) {
    w = { ...w, text: w.text.trim().replace(/\.$/, ",") };
  }
  for (const [from, to] of FIXED_TEXT) {
    if (w.text.trim().toLowerCase() === from) {
      w = { ...w, text: to };
    }
  }
  words.push(w);
  i += 1;
}

const out = words.map((w) => ({
  text: w.text.trim(),
  startMs: w.startMs,
  endMs: w.endMs,
  hasLeadingSpace: w.text.startsWith(" "),
}));

const ts = `// AUTO-GENERATED by scripts/generate-subtitles.mjs — do not edit by hand.
// Word-level karaoke captions for the Interstellar production.
// Source: whisper.cpp (small, language=id) on public/assets/interstellar/Voice.mp3
export type SubtitleWord = {
  text: string;
  /** ms since the start of the narration */
  startMs: number;
  endMs: number;
  /** whether whisper emitted a leading space before this word (spacing hint) */
  hasLeadingSpace: boolean;
};

export const SUBTITLE_WORDS: SubtitleWord[] = ${JSON.stringify(out, null, 2)
  .replace(/"text":/g, "text:")
  .replace(/"startMs":/g, "startMs:")
  .replace(/"endMs":/g, "endMs:")};

/** Words that receive the red accent when shown. */
export const EMPHASIS_WORDS = new Set([
  "nyata,",
  "nyata.",
  "Interstellar,",
  "Nolan,",
  "ayah",
  "anak.",
  "Murph,",
  "menyelamatkan",
  "jam",
  "tahun-tahun",
  "CGI,",
  "ditanam,",
  "miniatur",
  "raksasa",
  "kokpit.",
  "Zimmer",
  "emosional.",
  "membekas,",
  "komentar.",
]);

/** Narration starts at this offset inside the composition. */
export const NARRATION_OFFSET_MS = 0;
`;

fs.writeFileSync(path.join(ROOT, "src/projects/interstellar/subtitles.ts"), ts);
console.log("subtitles.ts written —", out.length, "words");
console.log(
  out.map((w) => w.text).join(" "),
);
