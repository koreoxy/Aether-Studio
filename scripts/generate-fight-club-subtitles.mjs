import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const caps = JSON.parse(
  fs.readFileSync(path.join(ROOT, "src/projects/fight-club/captions.json"), "utf-8"),
);

const words = caps.map((c) => ({
  text: c.text.trim(),
  startMs: c.startMs,
  endMs: c.endMs,
  hasLeadingSpace: c.text.startsWith(" "),
}));

const phrases = [];
let currentPhrase = [];
let pId = 1;

words.forEach((w, idx) => {
  currentPhrase.push(w);
  const isPunct = /[.!?]$/.test(w.text);
  const isComma = /[,]$/.test(w.text);
  if (currentPhrase.length >= 5 || isPunct || (isComma && currentPhrase.length >= 3) || idx === words.length - 1) {
    phrases.push({
      id: pId++,
      startMs: currentPhrase[0].startMs,
      endMs: currentPhrase[currentPhrase.length - 1].endMs,
      words: currentPhrase,
    });
    currentPhrase = [];
  }
});

const ts = `// AUTO-GENERATED by scripts/generate-fight-club-subtitles.mjs
export type SubtitleWord = {
  text: string;
  startMs: number;
  endMs: number;
  hasLeadingSpace: boolean;
};

export type SubtitlePhrase = {
  id: number;
  startMs: number;
  endMs: number;
  words: SubtitleWord[];
};

export const SUBTITLE_WORDS: SubtitleWord[] = ${JSON.stringify(words, null, 2)
  .replace(/"text":/g, "text:")
  .replace(/"startMs":/g, "startMs:")
  .replace(/"endMs":/g, "endMs:")
  .replace(/"hasLeadingSpace":/g, "hasLeadingSpace:")};

export const SUBTITLE_PHRASES: SubtitlePhrase[] = ${JSON.stringify(phrases, null, 2)
  .replace(/"id":/g, "id:")
  .replace(/"text":/g, "text:")
  .replace(/"startMs":/g, "startMs:")
  .replace(/"endMs":/g, "endMs:")
  .replace(/"words":/g, "words:")
  .replace(/"hasLeadingSpace":/g, "hasLeadingSpace:")};

export const EMPHASIS_WORDS = new Set([
  "Club:",
  "Fight",
  "Club.",
  "didiamkan.",
  "bawah",
  "tanah.",
  "besar:",
  "gerakan,",
  "sendiri.",
  "berkelahi.",
  "identitas,",
  "sendiri,",
  "dua",
  "kali.",
  "ready.",
  "know.",
]);

export const NARRATION_OFFSET_MS = 0;
`;

fs.writeFileSync(path.join(ROOT, "src/projects/fight-club/subtitles.ts"), ts);
console.log("fight-club subtitles.ts written —", words.length, "words,", phrases.length, "phrases");
